"""
Generate a LaTeX snippet summarizing CLIP evaluation results under `output/`.

Outputs:
  report/chapters/ch-experiments/tex/clip_results.tex

What it includes (per task):
  - average score + scoring mode
  - per-step table: step index, best candidate image, score, and object/state phrases

Run:
  python -u report/gen_clip_results.py --output_dir output
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple


def _read_json(path: Path) -> Dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _escape_tex(s: str) -> str:
    # Minimal escaping for table text
    return (
        s.replace("\\", "\\textbackslash{}")
        .replace("&", "\\&")
        .replace("%", "\\%")
        .replace("$", "\\$")
        .replace("#", "\\#")
        .replace("_", "\\_")
        .replace("{", "\\{")
        .replace("}", "\\}")
        .replace("~", "\\textasciitilde{}")
        .replace("^", "\\textasciicircum{}")
    )


def _discover_tasks(output_dir: Path) -> List[Path]:
    tasks = []
    for p in output_dir.iterdir():
        if p.is_dir() and not p.name.startswith("."):
            if (p / "clip_state_consistency_result.json").exists() and (p / "clip_intermediate_candidate_result.json").exists():
                tasks.append(p)
    return sorted(tasks, key=lambda x: x.name)


def _load_phrases(task_dir: Path) -> Dict[int, List[str]]:
    """
    Use text-derived expected phrases:
      ground_truth_object_phrases_text.json (source=text)
    """
    path = task_dir / "ground_truth_object_phrases_text.json"
    if not path.exists():
        return {}
    try:
        data = _read_json(path)
        if str(data.get("source", "")).strip().lower() not in {"text", ""}:
            return {}
        by_step = data.get("by_step", {}) or {}
        out: Dict[int, List[str]] = {}
        for k, v in by_step.items():
            try:
                out[int(k)] = [str(x).strip() for x in (v or []) if str(x).strip()]
            except Exception:
                continue
        return out
    except Exception:
        return {}
    return {}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output_dir", type=str, default=str(Path(__file__).resolve().parents[1] / "output"))
    args = parser.parse_args()

    output_dir = Path(args.output_dir).resolve()
    tasks = _discover_tasks(output_dir)
    if not tasks:
        raise SystemExit(f"No tasks found under {output_dir} with clip result JSONs.")

    out_tex = Path(__file__).resolve().parent / "chapters" / "ch-experiments" / "tex" / "clip_results.tex"
    out_tex.parent.mkdir(parents=True, exist_ok=True)

    lines: List[str] = []
    lines.append("% Auto-generated by report/gen_clip_results.py")
    lines.append("\\section{CLIP-based State Consistency Evaluation}")
    lines.append("\\label{sec:clip_eval}")
    lines.append(
        "We report state consistency using CLIP by comparing image embeddings against text embeddings derived from "
        "ground-truth state descriptions. In the object-phrase mode, each step is decomposed into five main "
        "object/state phrases (e.g., ``shimmering oil'', ``intact yolk''). If fewer than five valid phrases are available, "
        "the final score is the average cosine similarity across the available phrases."
    )
    lines.append("")

    for task_dir in tasks:
        task_name = task_dir.name.replace("_", " ")
        state_res = _read_json(task_dir / "clip_state_consistency_result.json")
        inter_res = _read_json(task_dir / "clip_intermediate_candidate_result.json")

        avg = float(state_res.get("average_score", 0.0))
        mode = str(state_res.get("scoring_mode", "unknown"))
        phrases_by_step = _load_phrases(task_dir)

        lines.append(f"\\subsection{{{_escape_tex(task_name.title())}}}")
        lines.append("\\begin{itemize}")
        lines.append(f"  \\item Average score: \\textbf{{{avg:.4f}}}")
        lines.append(f"  \\item Scoring mode: \\texttt{{{_escape_tex(mode)}}}")
        lines.append("\\end{itemize}")
        lines.append("")

        # Per-step table
        per_step = inter_res.get("per_step", []) or []
        lines.append("\\begin{tabularx}{\\textwidth}{p{1.3cm}p{5.0cm}X}")
        lines.append("\\toprule")
        lines.append("Step & Best candidate (score) & Objects/states (5 phrases)\\\\")
        lines.append("\\midrule")
        for row in per_step:
            step = row.get("step", "")
            best = row.get("best_candidate", "") or ""
            best_score = row.get("best_score", None)
            best_score_str = f"{float(best_score):.4f}" if isinstance(best_score, (int, float)) else "n/a"
            phrases = phrases_by_step.get(int(step), [])
            phrase_str = "; ".join([p for p in phrases[:5] if p.strip()])
            lines.append(
                f"{_escape_tex(str(step))} & "
                f"\\texttt{{{_escape_tex(best)}}} ({_escape_tex(best_score_str)}) & "
                f"{_escape_tex(phrase_str)}\\\\"
            )
        lines.append("\\bottomrule")
        lines.append("\\end{tabularx}")
        lines.append("")

    out_tex.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote: {out_tex}")


if __name__ == "__main__":
    main()


